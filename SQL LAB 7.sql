USE BANK;

SELECT * FROM LOAN;

SELECT LOAN_ID,CUSTOMER_ID,LOAN_AMT,RANK() OVER (order by LOAN_AMT DESC) AS RANKED_AMT FROM LOAN;

SELECT LOAN_ID,CUSTOMER_ID,LOAN_AMT,dense_rank() OVER(ORDER BY LOAN_AMT DESC) AS DENCE_RANK FROM LOAN;

SELECT LOAN_ID,CUSTOMER_ID,LOAN_AMT,row_number() OVER(ORDER BY LOAN_AMT DESC) AS DENCE_RANK FROM LOAN;
