---------- INNER JOIN
SELECT * FROM ACCOUNTS A
INNER JOIN TRANSACTIONS T
ON A.ACCOUNT_id = T.ACCOUNT_ID;

-------------- LEFT JOIN
SELECT * FROM ACCOUNTS A
LEFT JOIN TRANSACTIONS T
ON A.ACCOUNT_id = T.ACCOUNT_ID;

---------------- RIGHT JOIN
SELECT * FROM ACCOUNTS A
RIGHT JOIN TRANSACTIONS T
ON A.ACCOUNT_id = T.ACCOUNT_ID
WHERE T.TRANSACTION_TYPE = "DEPOSITE";

